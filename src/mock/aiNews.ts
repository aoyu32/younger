const formatDate = (index: number) => {
  const date = new Date(Date.UTC(2026, 8, 12));
  date.setUTCDate(date.getUTCDate() - index);
  return date.toISOString().slice(0, 10);
};

export const aiNewsData: AiNewsItem[] = aiNewsSeeds.map((seed, index) => {
  const viewCount = 4800 + ((index * 1379) % 26000);
  const likeCount = 120 + ((index * 83) % 780);
  const collectCount = 30 + ((index * 47) % 260);
  const date = latestDateMap[seed.id] ?? formatDate(index);
  const categoryLabel = categoryLabelMap.get(seed.category) ?? 'AI';
  const publishDate = `${date} ${String(9 + (index % 9)).padStart(2, '0')}:${String(
    (index * 7) % 60,
  ).padStart(2, '0')}`;

  return {
    id: seed.id,
    category: seed.category,
    title: seed.title,
    summary: seed.summary,
    cover: aiImagePool[index % aiImagePool.length],
    date,
    viewCount,
    likeCount,
    collectCount,
    author: {
      id: 200 + index,
      name: authors[index % authors.length],
    },
    publishDate,
    views: viewCount,
    likes: likeCount,
    favorites: collectCount,
    tags: Array.from(new Set([categoryLabel, ...seed.tags])),
    comments: Math.round(viewCount / 80),
    shares: Math.round(likeCount / 2),
    content: buildContent(seed, categoryLabel),
  };
});

